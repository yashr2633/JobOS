/**
 * The single navigation definition.
 *
 * The desktop rail (`Sidebar`) and the mobile bottom bar (`MobileNav`) both read
 * this list, so a destination can never appear in one and be missing from the
 * other — which is how a route becomes unreachable on a phone.
 *
 * Track My Jobs is deliberately absent and its route was NOT removed:
 * `/track-my-jobs` is a secondary detail route for genuine exceptions
 * (unresolved employer, held evidence), reached from the Gmail scan module. It
 * remains in `PROTECTED_PREFIXES` in `lib/supabase/middleware.ts`.
 */

export interface NavItem {
  href: string;
  label: string;
  /** Shorter label for the mobile bar, where horizontal room is scarce. */
  shortLabel: string;
  exact: boolean;
  icon: React.ReactNode;
  /**
   * Extra route prefixes this item owns, so a redirect or a stale link still
   * highlights the right destination instead of leaving nothing active.
   */
  alsoActiveFor?: readonly string[];
}

